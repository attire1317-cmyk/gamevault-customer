create or replace function public.gv_ping() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.live_pings(topic, ts) values (tg_argv[0], now())
  on conflict (topic) do update set ts = excluded.ts;
  return null;
end $$;

