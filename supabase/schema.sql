-- Order finished or cancelled -> tell the customer.
create or replace function public.gv_notify_order() returns trigger
language plpgsql security definer set search_path = public as $$
declare label text;
begin
  if new.status = old.status or new.status not in ('completed', 'cancelled') then return null; end if;
  if tg_table_name = 'orders' then
    select title into label from public.games where id = new.game_id;
  else
    select name into label from public.products where id = new.product_id;
  end if;
  insert into public.notifications(user_id, kind, title, body, link, dedupe)
  values (
    new.user_id,
    'order_' || new.status,
    case when new.status = 'completed' then 'Order completed' else 'Order cancelled' end,
    coalesce(label, 'Your order') || case when new.status = 'completed' then ' is ready. Thank you!' else ' was cancelled by the shop.' end,
    '/account',
    tg_table_name || ':' || new.id || ':' || new.status
  ) on conflict do nothing;
  return null;
end $$;

