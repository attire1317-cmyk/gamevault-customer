-- ---------------------------------------------------------------- tables
create table if not exists public.users (
  id            bigint generated by default as identity primary key,
  name          text not null,
  email         text not null unique,
  phone         text,
  password_hash text not null,
  role          text not null default 'customer' check (role in ('customer','admin')),
  failed_logins int  not null default 0,
  locked_until  timestamptz,
  created_at    timestamptz not null default now()
);

create table if not exists public.games (
  id           bigint generated by default as identity primary key,
  title        text not null,
  platform     text not null,
  genre        text not null default '',
  description  text not null default '',
  image_url    text not null default '',
  sale_price   int  not null default 0 check (sale_price >= 0),
  rent_per_day int  not null default 0 check (rent_per_day >= 0),
  stock_sale   int  not null default 0 check (stock_sale >= 0),
  stock_rent   int  not null default 0 check (stock_rent >= 0),
  active       boolean not null default true,
  trending     boolean not null default false,
  trending_at  timestamptz,
  created_at   timestamptz not null default now()
);

create table if not exists public.offers (
  id         bigint generated by default as identity primary key,
  title      text not null,
  percent    int  not null check (percent between 1 and 90),
  game_id    bigint references public.games(id) on delete cascade,
  applies_to text not null default 'both' check (applies_to in ('buy','rent','both')),
  starts_at  timestamptz not null,
  ends_at    timestamptz not null,
  active     boolean not null default true
);

create table if not exists public.rentals (
  id               bigint generated by default as identity primary key,
  user_id          bigint not null references public.users(id),
  game_id          bigint not null references public.games(id),
  days             int  not null,
  price_per_day    int  not null,
  discount_percent int  not null default 0,
  total            int  not null,
  started_at       timestamptz not null,
  due_at           timestamptz not null,
  returned_at      timestamptz,
  status           text not null default 'active' check (status in ('active','returned')),
  created_by       bigint references public.users(id)
);

create table if not exists public.orders (
  id               bigint generated by default as identity primary key,
  user_id          bigint not null references public.users(id),
  game_id          bigint not null references public.games(id),
  qty              int  not null,
  unit_price       int  not null,
  discount_percent int  not null default 0,
  total            int  not null,
  status           text not null default 'pending' check (status in ('pending','completed','cancelled')),
  created_at       timestamptz not null default now()
);

create table if not exists public.audit (
  id       bigint generated by default as identity primary key,
  ts       timestamptz not null default now(),
  actor_id bigint,
  action   text not null,
  detail   text
);

