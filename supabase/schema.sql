-- Saved item back in stock -> tell everyone who saved it.
create or replace function public.gv_notify_restock() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_table_name = 'games' then
    if new.active and ((old.stock_sale <= 0 and new.stock_sale > 0) or (old.stock_rent <= 0 and new.stock_rent > 0)) then
      insert into public.notifications(user_id, kind, title, body, link)
      select w.user_id, 'back_in_stock', new.title || ' is back',
             'Now available to ' || case when new.stock_rent > 0 and new.stock_sale > 0 then 'rent or buy' when new.stock_rent > 0 then 'rent' else 'buy' end || '.',
             '/games/' || new.id
      from public.wishlist w where w.game_id = new.id;
    end if;
  else
    if new.active and old.stock <= 0 and new.stock > 0 then
      insert into public.notifications(user_id, kind, title, body, link)
      select w.user_id, 'back_in_stock', new.name || ' is back', 'Back in stock now.', '/shop/' || new.id
      from public.wishlist w where w.product_id = new.id;
    end if;
  end if;
  return null;
end $$;

