create or replace function public.gv_create_product_order(p_user bigint, p_product bigint, p_qty int)
returns bigint language plpgsql as $$
declare p public.products; pct int; unit int; oid bigint;
begin
  select * into p from public.products where id = p_product and active for update;
  if not found then raise exception 'GV:404:Item not found.'; end if;
  if p.stock < p_qty then raise exception 'GV:409:Not enough in stock.'; end if;
  update public.products set stock = stock - p_qty where id = p_product;
  pct := case when p.discount_percent > 0 and (p.discount_ends_at is null or p.discount_ends_at > now()) then p.discount_percent else 0 end;
  unit := round(p.price * (100 - pct) / 100.0);
  insert into public.product_orders(user_id, product_id, qty, unit_price, total, status)
  values (p_user, p_product, p_qty, unit, unit * p_qty, 'pending') returning id into oid;
  insert into public.audit(actor_id, action, detail) values (p_user, 'product_order.create', format('order %s product %s qty %s', oid, p_product, p_qty));
  return oid;
end $$;

create or replace function public.gv_set_product_order_status(p_id bigint, p_status text, p_actor bigint)
returns bigint language plpgsql as $$
declare o public.product_orders;
begin
  if p_status not in ('completed', 'cancelled') then raise exception 'GV:422:Invalid status.'; end if;
  select * into o from public.product_orders where id = p_id for update;
  if not found then raise exception 'GV:404:Order not found.'; end if;
  if o.status <> 'pending' then raise exception 'GV:409:Only pending orders can be changed.'; end if;
  update public.product_orders set status = p_status where id = p_id;
  if p_status = 'cancelled' then
