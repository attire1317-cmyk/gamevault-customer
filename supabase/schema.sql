-- ---------------------------------------------------------------- business logic
-- Money and stock changes run inside these functions, so they are atomic:
-- two people can never take the last copy. Errors are 'GV:<http status>:<message>'.

create or replace function public.gv_best_percent(p_game bigint, p_kind text) returns int
language sql stable as $$
  select coalesce(max(percent), 0)::int from public.offers
  where active and starts_at <= now() and ends_at >= now()
    and (game_id is null or game_id = p_game)
    and (applies_to = 'both' or applies_to = p_kind);
$$;

create or replace function public.gv_create_rental(
  p_user bigint, p_game bigint, p_days int, p_created_by bigint, p_limit boolean
) returns bigint language plpgsql as $$
declare g public.games; c int; pct int; per_day int; rid bigint;
begin
  select * into g from public.games where id = p_game and active for update;
  if not found then raise exception 'GV:404:Game not found.'; end if;
  if p_limit then
    select count(*) into c from public.rentals where user_id = p_user and status = 'active';
    if c >= 5 then raise exception 'GV:409:You can have up to 5 active rentals at a time.'; end if;
  end if;
  if g.stock_rent < 1 then raise exception 'GV:409:No rental copies are available right now.'; end if;
  update public.games set stock_rent = stock_rent - 1 where id = p_game;
  pct := public.gv_best_percent(p_game, 'rent');
  per_day := round(g.rent_per_day * (100 - pct) / 100.0);
  insert into public.rentals(user_id, game_id, days, price_per_day, discount_percent, total, started_at, due_at, status, created_by)
  values (p_user, p_game, p_days, per_day, pct, per_day * p_days, now(), now() + make_interval(days => p_days), 'active', p_created_by)
  returning id into rid;
  insert into public.audit(actor_id, action, detail)
  values (coalesce(p_created_by, p_user), 'rental.create', format('rental %s game %s days %s', rid, p_game, p_days));
  return rid;
end $$;

create or replace function public.gv_extend_rental(p_id bigint, p_days int, p_actor bigint)
returns bigint language plpgsql as $$
declare r public.rentals;
begin
  select * into r from public.rentals where id = p_id for update;
  if not found then raise exception 'GV:404:Rental not found.'; end if;
  if r.status <> 'active' then raise exception 'GV:409:This rental was already returned.'; end if;
  update public.rentals
     set due_at = due_at + make_interval(days => p_days), days = days + p_days, total = total + price_per_day * p_days
   where id = p_id;
  insert into public.audit(actor_id, action, detail) values (p_actor, 'rental.extend', format('rental %s +%sd', p_id, p_days));
  return r.user_id;
end $$;

create or replace function public.gv_return_rental(p_id bigint, p_actor bigint)
returns bigint language plpgsql as $$
declare r public.rentals;
begin
  select * into r from public.rentals where id = p_id for update;
  if not found then raise exception 'GV:404:Rental not found.'; end if;
  if r.status <> 'active' then raise exception 'GV:409:This rental was already returned.'; end if;
  update public.rentals set status = 'returned', returned_at = now() where id = p_id;
  update public.games set stock_rent = stock_rent + 1 where id = r.game_id;
  insert into public.audit(actor_id, action, detail) values (p_actor, 'rental.return', format('rental %s', p_id));
  return r.user_id;
end $$;

create or replace function public.gv_create_order(p_user bigint, p_game bigint, p_qty int)
returns bigint language plpgsql as $$
declare g public.games; pct int; unit int; oid bigint;
begin
  select * into g from public.games where id = p_game and active for update;
  if not found then raise exception 'GV:404:Game not found.'; end if;
  if g.stock_sale < p_qty then raise exception 'GV:409:Not enough copies in stock.'; end if;
  update public.games set stock_sale = stock_sale - p_qty where id = p_game;
  pct := public.gv_best_percent(p_game, 'buy');
  unit := round(g.sale_price * (100 - pct) / 100.0);
  insert into public.orders(user_id, game_id, qty, unit_price, discount_percent, total, status)
  values (p_user, p_game, p_qty, unit, pct, unit * p_qty, 'pending') returning id into oid;
  insert into public.audit(actor_id, action, detail) values (p_user, 'order.create', format('order %s game %s qty %s', oid, p_game, p_qty));
  return oid;
end $$;

create or replace function public.gv_set_order_status(p_id bigint, p_status text, p_actor bigint)
returns bigint language plpgsql as $$
declare o public.orders;
begin
  if p_status not in ('completed', 'cancelled') then raise exception 'GV:422:Invalid status.'; end if;
  select * into o from public.orders where id = p_id for update;
  if not found then raise exception 'GV:404:Order not found.'; end if;
  if o.status <> 'pending' then raise exception 'GV:409:Only pending orders can be changed.'; end if;
  update public.orders set status = p_status where id = p_id;
  if p_status = 'cancelled' then
    update public.games set stock_sale = stock_sale + o.qty where id = o.game_id;
  end if;
  insert into public.audit(actor_id, action, detail) values (p_actor, 'order.' || p_status, format('order %s', p_id));
  return o.user_id;
end $$;

create or replace function public.gv_admin_stats() returns json
language sql stable as $$
  select json_build_object(
    'activeRentals', (select count(*) from public.rentals where status = 'active'),
    'overdue',       (select count(*) from public.rentals where status = 'active' and due_at < now()),
    'pendingOrders', (select count(*) from public.orders  where status = 'pending'),
    'games',         (select count(*) from public.games   where active),
    'customers',     (select count(*) from public.users   where role = 'customer'),
    'revenue',       (select coalesce(sum(total), 0) from public.rentals)
                   + (select coalesce(sum(total), 0) from public.orders where status = 'completed'),
    'dueSoon',       (select coalesce(json_agg(x), '[]'::json) from (
                        select r.id, r.due_at as "dueAt", g.title, u.name as "customerName"
                        from public.rentals r
                        join public.games g on g.id = r.game_id
                        join public.users u on u.id = r.user_id
                        where r.status = 'active' order by r.due_at asc limit 6) x)
  );
$$;

-- Used once by the old-data import script so new rows continue after the imported ids.
create or replace function public.gv_reset_sequences() returns void language plpgsql as $$
declare t text;
begin
  foreach t in array array['users','games','offers','rentals','orders','audit'] loop
    execute format(
      'select setval(pg_get_serial_sequence(%L, ''id''), greatest(coalesce((select max(id) from public.%I), 0), 1), (select count(*) > 0 from public.%I))',
      'public.' || t, t, t);
  end loop;
end $$;

-- Only the servers (service_role) may call the gv_* functions. Not the browser.
do $$
declare r record;
begin
  for r in
    select p.oid::regprocedure as sig
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname like 'gv\_%'
  loop
    execute format('revoke all on function %s from public, anon, authenticated', r.sig);
    execute format('grant execute on function %s to service_role', r.sig);
  end loop;
end $$;

