-- Rentals due within 2 days (or overdue): one reminder each. Returns how many were created.
create or replace function public.gv_notify_due_soon() returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  with ins as (
    insert into public.notifications(user_id, kind, title, body, link, dedupe)
    select r.user_id,
           case when r.due_at < now() then 'overdue' else 'due_soon' end,
           case when r.due_at < now() then 'Rental overdue' else 'Rental due soon' end,
           g.title || case when r.due_at < now() then ' was due back. Please return it.' else ' is due back ' || to_char(r.due_at at time zone 'Asia/Kolkata', 'DD Mon, HH12:MI AM') || '.' end,
           '/account',
           case when r.due_at < now() then 'overdue:' || r.id else 'due:' || r.id end
    from public.rentals r join public.games g on g.id = r.game_id
    where r.status = 'active' and r.due_at < now() + interval '2 days'
    on conflict do nothing
    returning 1)
  select count(*) into n from ins;
  return n;
end $$;

-- One order for a whole cart. Everything succeeds or nothing is created.
create or replace function public.gv_create_product_cart(p_user bigint, p_items jsonb)
returns bigint[] language plpgsql as $$
declare it jsonb; ids bigint[] := '{}';
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 20 then
    raise exception 'GV:422:Your cart is empty.';
  end if;
  for it in select e from jsonb_array_elements(p_items) e order by (e->>'productId')::bigint loop
    if (it->>'qty')::int not between 1 and 5 then raise exception 'GV:422:Invalid quantity.'; end if;
    ids := ids || public.gv_create_product_order(p_user, (it->>'productId')::bigint, (it->>'qty')::int);
  end loop;
  return ids;
end $$;

-- Admin overview now counts console and accessory orders too.
create or replace function public.gv_admin_stats() returns json
language sql stable as $$
  select json_build_object(
    'activeRentals', (select count(*) from public.rentals where status = 'active'),
    'overdue',       (select count(*) from public.rentals where status = 'active' and due_at < now()),
    'pendingOrders', (select count(*) from public.orders  where status = 'pending')
                   + (select count(*) from public.product_orders where status = 'pending'),
    'games',         (select count(*) from public.games   where active),
    'items',         (select count(*) from public.products where active),
    'lowStock',      (select count(*) from public.products where active and stock <= 2)
                   + (select count(*) from public.games where active and (stock_sale between 1 and 2 or stock_rent between 1 and 2)),
    'customers',     (select count(*) from public.users   where role = 'customer'),
    'revenue',       (select coalesce(sum(total), 0) from public.rentals)
                   + (select coalesce(sum(total), 0) from public.orders where status = 'completed')
                   + (select coalesce(sum(total), 0) from public.product_orders where status = 'completed'),
    'itemRevenue',   (select coalesce(sum(total), 0) from public.product_orders where status = 'completed'),
    'dueSoon',       (select coalesce(json_agg(x), '[]'::json) from (
                        select r.id, r.due_at as "dueAt", g.title, u.name as "customerName", u.phone as "customerPhone"
                        from public.rentals r
                        join public.games g on g.id = r.game_id
                        join public.users u on u.id = r.user_id
                        where r.status = 'active' order by r.due_at asc limit 6) x)
  );
$$;

do $$
declare r record;
begin
  for r in
    select p.oid::regprocedure as sig
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname in ('gv_notify_order','gv_notify_restock','gv_notify_due_soon','gv_create_product_cart','gv_admin_stats')
  loop
    execute format('revoke all on function %s from public, anon, authenticated', r.sig);
    execute format('grant execute on function %s to service_role', r.sig);
  end loop;
end $$;

