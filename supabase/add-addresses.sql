create table if not exists public.addresses (
  id         bigint generated by default as identity primary key,
  user_id    bigint not null references public.users(id) on delete cascade,
  label      text not null default 'Home' check (label in ('Home','Work','Other')),
  full_name  text not null,
  phone      text not null,
  line1      text not null,
  line2      text not null default '',
  city       text not null,
  state      text not null,
  pincode    text not null,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists idx_addresses_user on public.addresses(user_id);
-- at most one default address per customer
create unique index if not exists uq_addresses_default on public.addresses(user_id) where is_default;

-- at most 2 saved addresses per customer (enforced here, so no app bug can bypass it)
create or replace function public.gv_limit_addresses() returns trigger
language plpgsql as $$
begin
  if (select count(*) from public.addresses where user_id = new.user_id) >= 2 then
    raise exception 'GV:409:You can save up to 2 addresses. Delete one to add another.';
  end if;
  return new;
end $$;

drop trigger if exists gv_limit_addresses on public.addresses;
create trigger gv_limit_addresses before insert on public.addresses
  for each row execute function public.gv_limit_addresses();

-- Same lockdown as every other table: no public policies, only the servers can touch it.
alter table public.addresses enable row level security;

-- Every order keeps a copy of the address it was sent to, so editing or deleting
-- a saved address later never changes past orders. The admin app reads this column.
alter table public.rentals        add column if not exists address jsonb;
alter table public.orders         add column if not exists address jsonb;
alter table public.product_orders add column if not exists address jsonb;
