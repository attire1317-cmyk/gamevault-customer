-- ---------------------------------------------------------------- wishlist, notifications, cart, stats
-- Safe to run more than once. Run this in the Supabase SQL editor.
create table if not exists public.wishlist (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references public.users(id) on delete cascade,
  game_id     bigint references public.games(id) on delete cascade,
  product_id  bigint references public.products(id) on delete cascade,
  created_at  timestamptz not null default now(),
  check ((game_id is null) <> (product_id is null))
);
create unique index if not exists uq_wish_game    on public.wishlist(user_id, game_id)    where game_id is not null;
create unique index if not exists uq_wish_product on public.wishlist(user_id, product_id) where product_id is not null;

create table if not exists public.notifications (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references public.users(id) on delete cascade,
  kind        text   not null,
  title       text   not null,
  body        text   not null default '',
  link        text,
  dedupe      text,
  read_at     timestamptz,
  emailed_at  timestamptz,
  created_at  timestamptz not null default now()
);
create unique index if not exists uq_notif_dedupe on public.notifications(user_id, dedupe) where dedupe is not null;
create index if not exists idx_notif_user on public.notifications(user_id, created_at desc);

alter table public.wishlist      enable row level security;
alter table public.notifications enable row level security;

drop trigger if exists gv_ping_notifications on public.notifications;
create trigger gv_ping_notifications after insert on public.notifications for each statement execute function public.gv_ping('notifications');

-- Order finished or cancelled -> tell the customer.
create or replace function public.gv_notify_order() returns trigger
language plpgsql security definer set search_path = public as $$
declare label text;
begin
  if new.status = old.status or new.status not in ('completed', 'cancelled') then return null; end if;
  if tg_table_name = 'orders' then
    select title into label from public.games where id = new.game_id;
  else
    select name into label from public.products where id = new.product_id;
  end if;
  insert into public.notifications(user_id, kind, title, body, link, dedupe)
  values (
    new.user_id,
    'order_' || new.status,
    case when new.status = 'completed' then 'Order completed' else 'Order cancelled' end,
    coalesce(label, 'Your order') || case when new.status = 'completed' then ' is ready. Thank you!' else ' was cancelled by the shop.' end,
    '/account',
    tg_table_name || ':' || new.id || ':' || new.status
  ) on conflict do nothing;
  return null;
end $$;

drop trigger if exists gv_notify_orders on public.orders;
drop trigger if exists gv_notify_product_orders on public.product_orders;
create trigger gv_notify_orders         after update of status on public.orders         for each row execute function public.gv_notify_order();
create trigger gv_notify_product_orders after update of status on public.product_orders for each row execute function public.gv_notify_order();

-- Saved item back in stock -> tell everyone who saved it.
create or replace function public.gv_notify_restock() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_table_name = 'games' then
    if new.active and ((old.stock_sale <= 0 and new.stock_sale > 0) or (old.stock_rent <= 0 and new.stock_rent > 0)) then
      insert into public.notifications(user_id, kind, title, body, link)
      select w.user_id, 'back_in_stock', new.title || ' is back',
             'Now available to ' || case when new.stock_rent > 0 and new.stock_sale > 0 then 'rent or buy' when new.stock_rent > 0 then 'rent' else 'buy' end || '.',
             '/games/' || new.id
      from public.wishlist w where w.game_id = new.id;
    end if;
  else
    if new.active and old.stock <= 0 and new.stock > 0 then
      insert into public.notifications(user_id, kind, title, body, link)
      select w.user_id, 'back_in_stock', new.name || ' is back', 'Back in stock now.', '/shop/' || new.id
      from public.wishlist w where w.product_id = new.id;
    end if;
  end if;
  return null;
end $$;

drop trigger if exists gv_notify_restock_games on public.games;
drop trigger if exists gv_notify_restock_products on public.products;
create trigger gv_notify_restock_games    after update of stock_sale, stock_rent on public.games    for each row execute function public.gv_notify_restock();
create trigger gv_notify_restock_products after update of stock on public.products for each row execute function public.gv_notify_restock();

-- Rentals due within 2 days (or overdue): one reminder each. Returns how many were created.
create or replace function public.gv_notify_due_soon() returns int
language plpgsql security definer set search_path = public as $$
declare n int;
begin
  with ins as (
    insert into public.notifications(user_id, kind, title, body, link, dedupe)
    select r.user_id,
           case when r.due_at < now() then 'overdue' else 'due_soon' end,
           case when r.due_at < now() then 'Rental overdue' else 'Rental due soon' end,
           g.title || case when r.due_at < now() then ' was due back. Please return it.' else ' is due back ' || to_char(r.due_at at time zone 'Asia/Kolkata', 'DD Mon, HH12:MI AM') || '.' end,
           '/account',
           case when r.due_at < now() then 'overdue:' || r.id else 'due:' || r.id end
    from public.rentals r join public.games g on g.id = r.game_id
    where r.status = 'active' and r.due_at < now() + interval '2 days'
    on conflict do nothing
    returning 1)
  select count(*) into n from ins;
  return n;
end $$;

-- One order for a whole cart. Everything succeeds or nothing is created.
create or replace function public.gv_create_product_cart(p_user bigint, p_items jsonb)
returns bigint[] language plpgsql as $$
declare it jsonb; ids bigint[] := '{}';
begin
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 20 then
    raise exception 'GV:422:Your cart is empty.';
  end if;
  for it in select e from jsonb_array_elements(p_items) e order by (e->>'productId')::bigint loop
    if (it->>'qty')::int not between 1 and 5 then raise exception 'GV:422:Invalid quantity.'; end if;
    ids := ids || public.gv_create_product_order(p_user, (it->>'productId')::bigint, (it->>'qty')::int);
  end loop;
  return ids;
end $$;

-- Admin overview now counts console and accessory orders too.
create or replace function public.gv_admin_stats() returns json
language sql stable as $$
  select json_build_object(
    'activeRentals', (select count(*) from public.rentals where status = 'active'),
    'overdue',       (select count(*) from public.rentals where status = 'active' and due_at < now()),
    'pendingOrders', (select count(*) from public.orders  where status = 'pending')
                   + (select count(*) from public.product_orders where status = 'pending'),
    'games',         (select count(*) from public.games   where active),
    'items',         (select count(*) from public.products where active),
    'lowStock',      (select count(*) from public.products where active and stock <= 2)
                   + (select count(*) from public.games where active and (stock_sale between 1 and 2 or stock_rent between 1 and 2)),
    'customers',     (select count(*) from public.users   where role = 'customer'),
    'revenue',       (select coalesce(sum(total), 0) from public.rentals)
                   + (select coalesce(sum(total), 0) from public.orders where status = 'completed')
                   + (select coalesce(sum(total), 0) from public.product_orders where status = 'completed'),
    'itemRevenue',   (select coalesce(sum(total), 0) from public.product_orders where status = 'completed'),
    'dueSoon',       (select coalesce(json_agg(x), '[]'::json) from (
                        select r.id, r.due_at as "dueAt", g.title, u.name as "customerName", u.phone as "customerPhone"
                        from public.rentals r
                        join public.games g on g.id = r.game_id
                        join public.users u on u.id = r.user_id
                        where r.status = 'active' order by r.due_at asc limit 6) x)
  );
$$;

do $$
declare r record;
begin
  for r in
    select p.oid::regprocedure as sig
    from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname in ('gv_notify_order','gv_notify_restock','gv_notify_due_soon','gv_create_product_cart','gv_admin_stats')
  loop
    execute format('revoke all on function %s from public, anon, authenticated', r.sig);
    execute format('grant execute on function %s to service_role', r.sig);
  end loop;
end $$;
