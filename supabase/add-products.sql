-- ---------------------------------------------------------------- consoles & accessories
-- Safe to run more than once. Run this in the Supabase SQL editor.
create table if not exists public.products (
  id                bigint generated by default as identity primary key,
  name              text   not null,
  category          text   not null default 'console' check (category in ('console','controller','accessory')),
  brand             text   not null default '',
  description       text   not null default '',
  image_url         text   not null default '',
  price             int    not null check (price >= 0),
  stock             int    not null default 0 check (stock >= 0),
  discount_percent  int    not null default 0 check (discount_percent between 0 and 90),
  discount_ends_at  timestamptz,
  active            boolean not null default true,
  created_at        timestamptz not null default now()
);

create table if not exists public.product_orders (
  id          bigint generated by default as identity primary key,
  user_id     bigint not null references public.users(id),
  product_id  bigint not null references public.products(id),
  qty         int  not null,
  unit_price  int  not null,
  total       int  not null,
  status      text not null default 'pending' check (status in ('pending','completed','cancelled')),
  created_at  timestamptz not null default now()
);

create index if not exists idx_products_active on public.products(active, category);
create index if not exists idx_product_orders_user on public.product_orders(user_id);

alter table public.products       enable row level security;
alter table public.product_orders enable row level security;

drop trigger if exists gv_ping_products       on public.products;
drop trigger if exists gv_ping_product_orders on public.product_orders;
create trigger gv_ping_products       after insert or update or delete on public.products       for each statement execute function public.gv_ping('catalog');
create trigger gv_ping_product_orders after insert or update or delete on public.product_orders for each statement execute function public.gv_ping('orders');

create or replace function public.gv_create_product_order(p_user bigint, p_product bigint, p_qty int)
returns bigint language plpgsql as $$
declare p public.products; pct int; unit int; oid bigint;
begin
  select * into p from public.products where id = p_product and active for update;
  if not found then raise exception 'GV:404:Item not found.'; end if;
  if p.stock < p_qty then raise exception 'GV:409:Not enough in stock.'; end if;
  update public.products set stock = stock - p_qty where id = p_product;
  pct := case when p.discount_percent > 0 and (p.discount_ends_at is null or p.discount_ends_at > now()) then p.discount_percent else 0 end;
  unit := round(p.price * (100 - pct) / 100.0);
  insert into public.product_orders(user_id, product_id, qty, unit_price, total, status)
  values (p_user, p_product, p_qty, unit, unit * p_qty, 'pending') returning id into oid;
  insert into public.audit(actor_id, action, detail) values (p_user, 'product_order.create', format('order %s product %s qty %s', oid, p_product, p_qty));
  return oid;
end $$;

create or replace function public.gv_set_product_order_status(p_id bigint, p_status text, p_actor bigint)
returns bigint language plpgsql as $$
declare o public.product_orders;
begin
  if p_status not in ('completed', 'cancelled') then raise exception 'GV:422:Invalid status.'; end if;
  select * into o from public.product_orders where id = p_id for update;
  if not found then raise exception 'GV:404:Order not found.'; end if;
  if o.status <> 'pending' then raise exception 'GV:409:Only pending orders can be changed.'; end if;
  update public.product_orders set status = p_status where id = p_id;
  if p_status = 'cancelled' then
    update public.products set stock = stock + o.qty where id = o.product_id;
  end if;
  insert into public.audit(actor_id, action, detail) values (p_actor, 'product_order.' || p_status, format('order %s', p_id));
  return o.user_id;
end $$;

-- Only the servers (service_role) may call the gv_* functions.
revoke all on function public.gv_create_product_order(bigint, bigint, int) from public, anon, authenticated;
revoke all on function public.gv_set_product_order_status(bigint, text, bigint) from public, anon, authenticated;
grant execute on function public.gv_create_product_order(bigint, bigint, int) to service_role;
grant execute on function public.gv_set_product_order_status(bigint, text, bigint) to service_role;
